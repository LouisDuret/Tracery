/// Dessine un texte dans un tampon RGBA (non prémultiplié, opaque).
#[allow(clippy::too_many_arguments)]
pub fn draw_text(
    buf: &mut [u8],
    width: usize,
    height: usize,
    x: usize,
    y: usize,
    text: &str,
    scale: usize,
    rgb: [u8; 3],
) {
    let mut cx = x;
    for ch in text.chars() {
        let g = glyph(ch);
        for (row, bits) in g.iter().enumerate() {
            for col in 0..5 {
                if bits & (0x10 >> col) != 0 {
                    for dy in 0..scale {
                        for dx in 0..scale {
                            let px = cx + col * scale + dx;
                            let py = y + row * scale + dy;
                            if px < width && py < height {
                                let i = (py * width + px) * 4;
                                buf[i] = rgb[0];
                                buf[i + 1] = rgb[1];
                                buf[i + 2] = rgb[2];
                                buf[i + 3] = 255;
                            }
                        }
                    }
                }
            }
        }
        cx += 6 * scale;
    }
}
